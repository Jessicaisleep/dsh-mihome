"""Generate an offline MA-L lookup from a checksum-verified IEEE archive.

Download https://standards-oui.ieee.org/oui/oui.txt (or oui.csv), preserve that
archive, and record its SHA-256 and download date. This command never downloads
or guesses brands. Run from the repository root, for example:

    python scripts/update-oui.py --input /archive/oui.txt \
        --sha256 <64-hex-digest> --snapshot-date 2026-11-22 \
        --output python/smart_home/oui_table.py

Identical input bytes and arguments produce identical UTF-8/LF output. The
organization spelling is retained verbatim; an OUI is not a device category.
"""
from __future__ import annotations

import argparse
import csv
import datetime
import hashlib
import io
import json
import re
from pathlib import Path

IEEE_TXT_URL = "https://standards-oui.ieee.org/oui/oui.txt"
IEEE_CSV_URL = "https://standards-oui.ieee.org/oui/oui.csv"


def parse_archive(raw: bytes) -> tuple[dict[str, str], str, dict[str, list[str]]]:
    """Read official MA-L TXT/CSV; ambiguous legacy prefixes stay unknown.

    IEEE contains historic duplicate assignments (notably 080030). Choosing
    whichever row happens to be first would assign a potentially wrong name.
    See https://seclists.org/nmap-dev/2015/q2/321 and the IEEE archive itself.
    """
    text = raw.decode("utf-8-sig")
    assignments: dict[str, set[str]] = {}

    def add(prefix: str, organization: str) -> None:
        prefix, organization = prefix.strip().upper(), organization.strip()
        if not re.fullmatch(r"[0-9A-F]{6}", prefix) or not organization:
            raise ValueError("Invalid MA-L assignment or empty organization")
        assignments.setdefault(prefix, set()).add(organization)

    if text.startswith("Registry,"):
        for row in csv.DictReader(io.StringIO(text)):
            if row.get("Registry") == "MA-L":
                add(row.get("Assignment", ""), row.get("Organization Name", ""))
        source_url = IEEE_CSV_URL
    else:
        for match in re.finditer(r"(?m)^\s*([0-9A-Fa-f]{6})[ \t]+\(base 16\)[ \t]+([^\r\n]+)", text):
            add(match.group(1), match.group(2))
        source_url = IEEE_TXT_URL
    if not assignments:
        raise ValueError("The input contains no IEEE MA-L assignments")
    entries = {prefix: next(iter(names)) for prefix, names in assignments.items() if len(names) == 1}
    ambiguous = {prefix: sorted(names) for prefix, names in assignments.items() if len(names) > 1}
    return entries, source_url, ambiguous


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--input", type=Path, required=True, help="Archived IEEE oui.txt or oui.csv")
    parser.add_argument("--output", type=Path, required=True, help="Generated Python module")
    parser.add_argument("--snapshot-date", required=True, help="Archive acquisition date, YYYY-MM-DD")
    parser.add_argument("--sha256", required=True, help="Expected SHA-256 of the original archive bytes")
    args = parser.parse_args(argv)
    if datetime.date.fromisoformat(args.snapshot_date).isoformat() != args.snapshot_date:
        raise ValueError("snapshot-date must use YYYY-MM-DD")
    expected = args.sha256.lower()
    if not re.fullmatch(r"[0-9a-f]{64}", expected):
        raise ValueError("sha256 must contain 64 hexadecimal digits")
    raw = args.input.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != expected:
        raise ValueError(f"IEEE archive SHA-256 mismatch: expected {expected}, got {digest}")
    entries, source_url, ambiguous = parse_archive(raw)
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    lines = [
        "# SPDX-License-Identifier: GPL-3.0-or-later",
        '\"\"\"IEEE MA-L prefix -> registered organization (not brand or category).',
        "",
        "Generated by scripts/update-oui.py from the checksum-verified IEEE archive.",
        "Preserve the source archive to reproduce this module; do not hand-edit names.",
        '\"\"\"',
        "from __future__ import annotations",
        "",
        f"SOURCE_URL = {quote(source_url)}",
        f"SOURCE_SNAPSHOT_DATE = {quote(args.snapshot_date)}",
        f"SOURCE_SHA256 = {quote(digest)}",
        f"SOURCE_ENTRY_COUNT = {len(entries)}",
        "# These legacy assignments have several organizations; lookup returns unknown.",
        f"AMBIGUOUS_ASSIGNMENTS: dict[str, list[str]] = {json.dumps(dict(sorted(ambiguous.items())), ensure_ascii=False)}",
        "",
        "OUI_TABLE: dict[str, str] = {",
    ]
    lines.extend(f"    {quote(prefix)}: {quote(organization)}," for prefix, organization in sorted(entries.items()))
    lines.extend(["}", ""])
    # write_bytes avoids platform newline conversion, keeping hashes reproducible.
    args.output.write_bytes("\n".join(lines).encode("utf-8"))
    print(f"Generated {len(entries)} IEEE MA-L entries; source SHA-256 {digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
